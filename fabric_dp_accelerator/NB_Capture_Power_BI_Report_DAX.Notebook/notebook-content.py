def power_bi_request(method, path, body=None):
    token = notebookutils.credentials.getToken("pbi")
    response = requests.request(
        method,
        f"https://api.powerbi.com/v1.0/myorg/{path.lstrip('/')}",
        headers={
            "Authorization": f"Bearer {token}",
            "Content-Type": "application/json",
        },
        json=body,
        timeout=120,
    )
    if not response.ok:
        raise RuntimeError(
            f"Power BI API {method} {path} failed ({response.status_code}): "
            f"{response.text[:2000]}"
        )
    if not response.content:
        return {}
    payload = response.json()
    if not isinstance(payload, dict):
        raise RuntimeError(f"Power BI API {method} {path} returned invalid JSON.")
    return payload


def read_report_requests(path):
    csv_path = Path(path)
    if not csv_path.is_file():
        raise FileNotFoundError(
            f"Report input CSV does not exist: {csv_path}. Expected columns: "
            "workspace_name,report_name and optional enabled."
        )
    rows = pd.read_csv(csv_path, dtype=str, keep_default_na=False)
    required = {"workspace_name", "report_name"}
    missing = sorted(required - set(rows.columns))
    if missing:
        raise ValueError(f"{csv_path} is missing required columns: {', '.join(missing)}")
    unknown = sorted(set(rows.columns) - required - {"enabled"})
    if unknown:
        raise ValueError(f"{csv_path} has unknown columns: {', '.join(unknown)}")

    requests_to_run = []
    seen = set()
    for row_number, row in rows.iterrows():
        workspace_name = str(row["workspace_name"]).strip()
        report_name = str(row["report_name"]).strip()
        enabled = str(row.get("enabled", "true") or "true").strip().casefold()
        if enabled not in {"true", "false"}:
            raise ValueError(
                f"{csv_path}: row {row_number + 2} enabled must be true or false."
            )
        if enabled == "false":
            continue
        if not workspace_name or not report_name:
            raise ValueError(
                f"{csv_path}: row {row_number + 2} requires workspace_name and report_name."
            )
        key = (workspace_name.casefold(), report_name.casefold())
        if key in seen:
            raise ValueError(
                f"{csv_path}: duplicate report mapping at row {row_number + 2}: "
                f"{workspace_name}/{report_name}."
            )
        seen.add(key)
        requests_to_run.append((workspace_name, report_name))
    if not requests_to_run:
        raise ValueError(f"{csv_path} contains no enabled reports.")
    return tuple(requests_to_run)


def safe_folder_name(value):
    name = re.sub(r'[<>:"/\\|?*\x00-\x1f]+', "_", value).strip(" .")
    return name or "unnamed"


def find_column(dataframe, *names):
    folded = {
        str(column).replace(" ", "").casefold(): str(column)
        for column in dataframe.columns
    }
    for name in names:
        match = folded.get(name.replace(" ", "").casefold())
        if match:
            return match
    return None


def resolve_report(workspace_name, report_name):
    workspace_id = str(fabric.resolve_workspace_id(workspace_name))
    payload = power_bi_request("GET", f"groups/{workspace_id}/reports")
    matches = [
        report
        for report in payload.get("value", [])
        if isinstance(report, dict)
        and str(report.get("name") or "").strip().casefold()
        == report_name.strip().casefold()
    ]
    if not matches:
        raise RuntimeError(
            f"Report '{report_name}' was not found in workspace '{workspace_name}'."
        )
    if len(matches) > 1:
        raise RuntimeError(
            f"Multiple reports named '{report_name}' were found in workspace "
            f"'{workspace_name}'."
        )
    report_id = str(matches[0].get("id") or "")
    if not report_id:
        raise RuntimeError(f"Report '{workspace_name}/{report_name}' did not return an ID.")
    details = power_bi_request("GET", f"groups/{workspace_id}/reports/{report_id}")
    model_id = str(details.get("datasetId") or "")
    model_workspace_id = str(details.get("datasetWorkspaceId") or workspace_id)
    if not model_id:
        raise RuntimeError(
            f"Report '{workspace_name}/{report_name}' did not return a semantic model ID."
        )
    model_details = power_bi_request(
        "GET",
        f"groups/{model_workspace_id}/datasets/{model_id}",
    )
    model_name = str(model_details.get("name") or "").strip()
    if not model_name:
        raise RuntimeError(
            f"Semantic model '{model_id}' in workspace '{model_workspace_id}' "
            "did not return a name."
        )
    try:
        model_workspace_name = str(fabric.resolve_workspace_name(model_workspace_id))
    except Exception:
        model_workspace_name = workspace_name
    return {
        "workspaceName": workspace_name,
        "workspaceId": workspace_id,
        "reportName": report_name,
        "reportId": report_id,
        "semanticModelName": model_name,
        "semanticModelId": model_id,
        "semanticModelWorkspaceName": model_workspace_name,
        "semanticModelWorkspaceId": model_workspace_id,
    }


def list_report_pages(workspace_id, report_id):
    payload = power_bi_request("GET", f"groups/{workspace_id}/reports/{report_id}/pages")
    return [
        {
            "pageId": str(page.get("name") or ""),
            "pageName": str(page.get("displayName") or page.get("name") or ""),
            "order": page.get("order"),
        }
        for page in payload.get("value", [])
        if isinstance(page, dict)
    ]


def render_report_with_export(source):
    workspace_id = source["workspaceId"]
    report_id = source["reportId"]
    export = power_bi_request(
        "POST",
        f"groups/{workspace_id}/reports/{report_id}/ExportTo",
        body={
            "format": "PDF",
            "powerBIReportConfiguration": {
                "settings": {"includeHiddenPages": False}
            },
        },
    )
    export_id = str(export.get("id") or "")
    if not export_id:
        raise RuntimeError(f"Report export did not return an ID: {export}")

    deadline = time.monotonic() + int(capture_timeout_seconds)
    previous = ""
    while time.monotonic() < deadline:
        status = power_bi_request(
            "GET",
            f"groups/{workspace_id}/reports/{report_id}/exports/{export_id}",
        )
        state = str(status.get("status") or "")
        current = f"{state} ({status.get('percentComplete')}%)"
        if current != previous:
            print(f"  Export: {current}")
            previous = current
        if state.casefold() == "succeeded":
            return status
        if state.casefold() == "failed":
            raise RuntimeError(f"Report export failed: {status}")
        time.sleep(int(export_poll_seconds))
    raise TimeoutError(
        f"Report export did not finish within {capture_timeout_seconds} seconds."
    )


def get_trace_logs(trace):
    with warnings.catch_warnings():
        warnings.filterwarnings(
            "ignore",
            message="No trace logs have been recorded",
            category=UserWarning,
        )
        logs = trace.get_trace_logs()
    return logs if isinstance(logs, pd.DataFrame) else pd.DataFrame()


def normalize_dax(value):
    text = "" if value is None else str(value)
    text = text.replace("\r\n", "\n").replace("\r", "\n").strip()
    return re.sub(
        r"\s*\[WaitTime:\s*\d+(?:\.\d+)?\s*ms\]\s*$",
        "",
        text,
        flags=re.IGNORECASE,
    ).rstrip()


def result_set_count(dax_query):
    return len(tuple(re.finditer(r"(?im)^[ \t]*EVALUATE\b", dax_query)))


def application_source(value):
    if value is None or (not isinstance(value, (dict, list)) and pd.isna(value)):
        return "", ""
    try:
        context = value if isinstance(value, dict) else json.loads(str(value))
    except (TypeError, ValueError, json.JSONDecodeError):
        return "", ""
    sources = context.get("Sources") if isinstance(context, dict) else None
    if not isinstance(sources, list) or not sources or not isinstance(sources[0], dict):
        return "", ""
    return str(sources[0].get("ReportId") or ""), str(sources[0].get("VisualId") or "")


def trace_event_failed(value):
    if value is None or (not isinstance(value, (dict, list)) and pd.isna(value)):
        return False
    if isinstance(value, bool):
        return not value
    return str(value).strip().casefold() in {"0", "false", "failed", "failure"}


def captured_query_events(logs, report_id):
    if logs.empty:
        return pd.DataFrame()
    event_column = find_column(logs, "Event Class", "EventClass")
    text_column = find_column(logs, "Text Data", "TextData")
    if not event_column or not text_column:
        raise RuntimeError(
            f"Trace output is missing Event Class or Text Data: {list(logs.columns)}"
        )

    context_column = find_column(logs, "Application Context", "ApplicationContext")
    request_column = find_column(logs, "Request ID", "RequestID")
    duration_column = find_column(logs, "Duration")
    cpu_column = find_column(logs, "Cpu Time", "CpuTime")
    success_column = find_column(logs, "Success")
    application_column = find_column(logs, "Application Name", "ApplicationName")

    records = []
    query_end_rows = logs[logs[event_column].astype(str).str.casefold().eq("queryend")]
    for _, row in query_end_rows.iterrows():
        success = row.get(success_column) if success_column else None
        if trace_event_failed(success):
            continue
        dax_query = normalize_dax(row.get(text_column))
        if not re.match(
            r"^(?:DEFINE\b[\s\S]*\bEVALUATE\b|EVALUATE\b)",
            dax_query,
            re.IGNORECASE,
        ):
            continue
        captured_report_id, visual_id = application_source(
            row.get(context_column) if context_column else None
        )
        if captured_report_id and captured_report_id.casefold() != report_id.casefold():
            continue
        records.append(
            {
                "query_id": hashlib.sha256(dax_query.encode("utf-8")).hexdigest(),
                "report_id": captured_report_id or report_id,
                "visual_id": visual_id,
                "request_id": str(row.get(request_column) or "") if request_column else "",
                "duration_ms": int(row.get(duration_column) or 0) if duration_column else 0,
                "cpu_ms": int(row.get(cpu_column) or 0) if cpu_column else 0,
                "success": success,
                "application": str(row.get(application_column) or "") if application_column else "",
                "dax_query": dax_query,
            }
        )
    events = pd.DataFrame.from_records(records)
    if events.empty:
        return events
    matching = events[events["report_id"].str.casefold() == report_id.casefold()]
    return (matching if not matching.empty else events).reset_index(drop=True)


def trace_diagnostics(logs):
    if logs.empty:
        return "Trace returned zero rows."
    event_column = find_column(logs, "Event Class", "EventClass")
    counts = (
        logs[event_column].astype(str).value_counts(dropna=False).to_dict()
        if event_column
        else {}
    )
    success_column = find_column(logs, "Success")
    success_counts = (
        logs[success_column].astype(str).value_counts(dropna=False).to_dict()
        if success_column
        else {}
    )
    return f"eventCounts={counts}, successCounts={success_counts}"


def build_capture(events, source, pages):
    queries = []
    for query_id, rows in events.groupby("query_id", sort=True):
        dax_query = rows["dax_query"].iloc[0]
        durations = [int(value) for value in rows["duration_ms"].tolist()]
        cpu_values = [int(value) for value in rows["cpu_ms"].tolist()]
        queries.append(
            {
                "queryId": query_id,
                "resultSetCount": result_set_count(dax_query),
                "executionCount": len(rows),
                "visualIds": sorted({value for value in rows["visual_id"] if value}),
                "requestIds": sorted({value for value in rows["request_id"] if value}),
                "sourceDurationMs": durations,
                "sourceMedianDurationMs": statistics.median(durations) if durations else 0,
                "sourceCpuMs": cpu_values,
                "dax": dax_query,
            }
        )
    return {
        "version": 2,
        "captureMethod": "power-bi-report-export-sempy-trace",
        "readOnly": True,
        "capturedUtc": datetime.now(timezone.utc).isoformat(),
        "coverage": {
            "pageMode": "all-visible-pages",
            "pages": pages,
            "capturedVisualIds": sorted(
                {
                    visual_id
                    for query in queries
                    for visual_id in query["visualIds"]
                }
            ),
        },
        "source": source,
        "executionCount": int(len(events)),
        "uniqueQueryCount": len(queries),
        "resultSetCount": sum(query["resultSetCount"] for query in queries),
        "queries": queries,
    }


def capture_report(workspace_name, report_name):
    source = resolve_report(workspace_name, report_name)
    pages = list_report_pages(source["workspaceId"], source["reportId"])
    trace_logs = pd.DataFrame()

    with fabric.create_trace_connection(
        dataset=source["semanticModelName"],
        workspace=source["semanticModelWorkspaceId"],
    ) as trace_connection:
        with trace_connection.create_trace(QUERY_TRACE_SCHEMA) as trace:
            try:
                trace.start(delay=3)
            except Exception as exc:
                raise RuntimeError(
                    "Could not start the Analysis Services trace for semantic model "
                    f"'{source['semanticModelName']}' in workspace "
                    f"'{source['semanticModelWorkspaceName']}'. Power BI Premium "
                    "traces require database-administrator access; Build permission "
                    "is not sufficient. Run the notebook as an identity with "
                    "Contributor, Member, or Admin access in the semantic-model "
                    "workspace. The PDF export was not started. "
                    f"Original error: {exc}"
                ) from exc
            render_report_with_export(source)
            time.sleep(int(trace_settle_seconds))
            stopped_logs = trace.stop(timeout=10)
            trace_logs = (
                stopped_logs
                if isinstance(stopped_logs, pd.DataFrame)
                else get_trace_logs(trace)
            )

    events = captured_query_events(trace_logs, source["reportId"])
    if events.empty:
        raise RuntimeError(
            "The report export completed but no report DAX QueryEnd events were "
            f"captured. {trace_diagnostics(trace_logs)}"
        )
    return build_capture(events, source, pages)


def write_capture(capture):
    source = capture["source"]
    report_directory = (
        Path(output_root)
        / safe_folder_name(source["workspaceName"])
        / safe_folder_name(source["reportName"])
    )
    history_directory = report_directory / "history"
    history_directory.mkdir(parents=True, exist_ok=True)

    timestamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    latest_path = report_directory / "report-dax-queries.json"
    history_path = history_directory / f"report-dax-queries-{timestamp}.json"
    payload = json.dumps(capture, indent=2, sort_keys=True, default=str) + "\n"
    latest_path.write_text(payload, encoding="utf-8")
    history_path.write_text(payload, encoding="utf-8")
    return latest_path, history_path


def run_capture():
    report_requests = read_report_requests(reports_csv)
    outcomes = []
    failures = []

    for index, (workspace_name, report_name) in enumerate(report_requests, start=1):
        print(
            f"[{index}/{len(report_requests)}] Capturing "
            f"{workspace_name}/{report_name}"
        )
        started = time.perf_counter()
        try:
            capture = capture_report(workspace_name, report_name)
            latest_path, history_path = write_capture(capture)
            outcomes.append(
                {
                    "Workspace": workspace_name,
                    "Report": report_name,
                    "Status": "Passed",
                    "Pages": len(capture["coverage"]["pages"]),
                    "Visuals": len(capture["coverage"]["capturedVisualIds"]),
                    "Queries": capture["uniqueQueryCount"],
                    "Result Sets": capture["resultSetCount"],
                    "Duration (s)": round(time.perf_counter() - started, 1),
                    "Output": str(latest_path),
                }
            )
            print(
                f"  Captured {capture['uniqueQueryCount']} queries / "
                f"{capture['resultSetCount']} result sets."
            )
            print(f"  Latest: {latest_path}")
            print(f"  History: {history_path}")
        except Exception as exc:
            failures.append(f"{workspace_name}/{report_name}: {exc}")
            outcomes.append(
                {
                    "Workspace": workspace_name,
                    "Report": report_name,
                    "Status": "Failed",
                    "Pages": 0,
                    "Visuals": 0,
                    "Queries": 0,
                    "Result Sets": 0,
                    "Duration (s)": round(time.perf_counter() - started, 1),
                    "Output": "",
                }
            )
            print(f"  FAILED: {exc}")

    summary = pd.DataFrame(outcomes)
    display(summary)
    if failures:
        raise RuntimeError(
            f"{len(failures)} report capture(s) failed:\n- " + "\n- ".join(failures)
        )
    return summary

