# # Capture Power BI Report DAX
# # Captures the DAX generated by all visible pages of selected Power BI reports.
# The report and semantic model remain read-only. Temporary PDF exports render the
# report pages while a Semantic Link trace records QueryEnd events. For thin reports,
# the semantic model is resolved and traced in its separate workspace automatically.
# Power BI traces require database-administrator access to the semantic model.
# Build permission provides database-reader access and cannot start the trace.
# # 1. Attach a default Lakehouse to this notebook.
# 2. Upload a CSV with `workspace_name,report_name` and optional `enabled` columns.
# 3. Set `reports_csv` and `output_root` in the parameter cell.
# 4. Run all cells.
# 5. Download each generated report folder into the matching repository environment:
#    `data_pipelines/<environment>/migration_validation/report_dax_queries/`.

